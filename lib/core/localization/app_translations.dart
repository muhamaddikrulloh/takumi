  static String t(Locale locale, String key, {Map<String, String>? args}) {
    final lang = _translations[locale.languageCode] ?? _translations['id']!;
    String result = lang[key] ?? _translations['id']![key] ?? key;
    if (args != null) {
      args.forEach((k, v) => result = result.replaceAll('{$k}', v));
    }
    return result;
  }

  static String tCurrent(
    BuildContext context,
    String key, {
    Map<String, String>? args,
  }) {
    return t(Localizations.localeOf(context), key, args: args);
  }
}

